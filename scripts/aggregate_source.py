"""Generate the lecturer's record-keeping source from reachable production modules."""

import argparse
import ast
from hashlib import sha256
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'submission/production_source.py'


def local_dependency(node):
    if isinstance(node, ast.ImportFrom):
        if node.level == 1:
            return Path('cv_verifier') / f'{node.module}.py'
        if node.module and node.module.startswith('cv_verifier.'):
            return Path(*node.module.split('.')).with_suffix('.py')
    return None


def production_sources():
    """Return each reachable source once, dependencies first, in stable order."""
    ordered, visiting, visited = [], set(), set()
    def visit(path):
        if path in visiting:
            raise ValueError(f'Circular local import: {path}')
        if path in visited:
            return
        visiting.add(path)
        tree = ast.parse((ROOT / path).read_text())
        dependencies = {local_dependency(node) for node in ast.walk(tree)} - {None}
        for dependency in sorted(dependencies):
            visit(dependency)
        visiting.remove(path)
        visited.add(path)
        ordered.append(path)
    visit(Path('hw2.py'))
    return ordered


def generate():
    sections = ['#!/usr/bin/env python3\n'
                '# GENERATED by python -m scripts.aggregate_source; DO NOT EDIT.\n'
                '# Lecturer record keeping only. Run the authoritative modular hw2.py.\n'
                'from __future__ import annotations\n']
    definitions = set()
    for path in production_sources():
        source = (ROOT / path).read_text()
        tree = ast.parse(source)
        removed = set()
        for node in ast.walk(tree):
            if local_dependency(node) or (isinstance(node, ast.ImportFrom) and node.module == '__future__'):
                removed.update(range(node.lineno, node.end_lineno + 1))
        for node in tree.body:
            if isinstance(node, (ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)):
                if node.name in definitions:
                    raise ValueError(f'Duplicate top-level definition: {node.name}')
                definitions.add(node.name)
        body = ''.join(line for index, line in enumerate(source.splitlines(keepends=True), 1)
                       if index not in removed)
        sections.append(f'# Source: {path.as_posix()}\n# SHA256: {sha256(source.encode()).hexdigest()}\n' + body.strip() + '\n')
    result = '\n\n'.join(sections)
    compile(result, str(OUTPUT), 'exec')
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail if the checked-in aggregate is stale')
    args = parser.parse_args()
    source = generate()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text() != source:
            raise SystemExit('Aggregate is stale; run python -m scripts.aggregate_source')
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(source)
    print(f'{len(production_sources())} source files; {len(source.splitlines())} aggregated lines; {OUTPUT}')


if __name__ == '__main__':
    main()
